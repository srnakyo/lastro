import { beforeEach, describe, expect, it } from "bun:test";
import { docBuildsService, packagesService, questionsService, requirementsService } from "@lastro/core";
import { storeFromEnv } from "@lastro/storage";
import { buildDocs, packageReportMarkdown } from "../../apps/web/src/server/docs";
import { seedShop } from "../../scripts/demo/seed-shop";
import { resetDatabase } from "../helpers/db";
import { createBriefSource, createProject } from "../helpers/fixtures";

beforeEach(resetDatabase);

const text = (bytes: Uint8Array) => new TextDecoder().decode(bytes);

describe("documentation", () => {
  it("builds every document in Markdown, HTML with drawn diagrams and PDF, and keeps the latest build", async () => {
    const { workspace, actor } = await createProject();
    const shop = await seedShop(workspace.id, actor);
    const result = await buildDocs(shop.id, actor);
    expect(result).toEqual({ documents: 11, pdf: true });
    const latest = await docBuildsService.latest(shop.id);
    expect(latest).toHaveLength(33);

    const store = storeFromEnv();
    const report = text((await docBuildsService.read(shop.id, "client-report", "md", store)).bytes);
    expect(report).toContain("> The checkout accepts PIX and card, and shows the total before confirming.");
    const cases = text((await docBuildsService.read(shop.id, "test-cases", "md", store)).bytes);
    expect(cases).toContain("tests/coupon.test.ts::floors the total at shipping");
    const diagrams = text((await docBuildsService.read(shop.id, "diagrams", "html", store)).bytes);
    expect(diagrams).toContain("<svg");
    const pdf = (await docBuildsService.read(shop.id, "quality-report", "pdf", store)).bytes;
    expect(text(pdf.slice(0, 5))).toBe("%PDF-");
  }, 120_000);

  it("writes in the project's language", async () => {
    const { workspace, actor } = await createProject();
    const shop = await seedShop(workspace.id, actor);
    await buildDocs(shop.id, actor, { lang: "pt-BR", only: ["test-plan"], pdf: false });
    const plan = text((await docBuildsService.read(shop.id, "test-plan", "md", storeFromEnv())).bytes);
    expect(plan).toContain("# Plano de testes: Shop demo");
  }, 60_000);
});

describe("documents and the package report", () => {
  it("starts every document with the commit and the date, and groups requirements by package (REQ-P0V3Y)", async () => {
    const { workspace, actor } = await createProject();
    const shop = await seedShop(workspace.id, actor);
    await buildDocs(shop.id, actor, { only: ["requirements"], pdf: false, commit: "c0ffee1" });
    const md = text((await docBuildsService.read(shop.id, "requirements", "md", storeFromEnv())).bytes);
    expect(md.split("\n")[0]).toMatch(/^_Commit c0ffee1 · Generated by Lastro on .+\._$/);
    expect(md).toContain("# No package");
  });

  it("lists a package's items in the requester's order, and an item with an open question only under 'Awaiting answer' (REQ-D1F4M)", async () => {
    const { project, actor } = await createProject();
    const items = Array.from({ length: 12 }, (_, i) => `Item number ${i + 1} must work.`);
    const source = await createBriefSource(project.id, actor, false, `# Brief\n\n${items.join("\n\n")}\n`);
    const pkg = await packagesService.create(project.id, actor, { title: "Round 1", sources: [source.code] });
    for (const n of [12, 3, 7, 1, 10, 2, 5, 4, 6, 8, 9, 11]) {
      await requirementsService.create(project.id, actor, {
        title: `Item ${n}`, type: "behavior", statement: `Does item ${n}.`, package: pkg.code,
        citations: [{ source: source.code, anchor: "@brief.md#brief", label: String(n), quote: `Item number ${n} must work.` }],
        criteria: [{ code: "AC-1", text: `item ${n} works`, tests: [] }],
      });
    }
    const seven = (await requirementsService.list(project.id)).find((r) => r.title === "Item 7");
    await questionsService.ask(project.id, actor, { text: "Which plan does item 7 apply to?", askedTo: "client", requirements: [seven?.code ?? ""] });
    const report = await packageReportMarkdown(project.id, pkg.code);
    const [main, awaiting] = report.split("## Awaiting answer");
    const order = [...(main ?? "").matchAll(/## Item (\d+):/g)].map((m) => Number(m[1]));
    expect(order).toEqual([1, 2, 3, 4, 5, 6, 8, 9, 10, 11, 12]);
    expect(awaiting).toContain("Item 7: Item 7");
    expect(awaiting).toContain("Which plan does item 7 apply to?");
  });
});
