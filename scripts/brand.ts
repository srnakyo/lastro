/**
 * Builds the code side of the brand from the drawn files in docs/brand/:
 * - packages/shared/src/brand.ts, the path data the dashboard and the documents draw inline;
 * - apps/web/public/favicon.svg, a copy of the pixel-fitted favicon.
 * Run after changing any SVG in docs/brand/: `bun scripts/brand.ts`.
 */
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const brandDir = join(root, "docs", "brand");

/**
 * The SVGs drawn in currentColor, by the name they get in code. `mark28` and `lockupSidebar` are fitted to the
 * pixel grid (straight edges on whole pixels, curves true) and must be drawn 1:1, or they blur on 1x screens.
 */
const SHAPES = {
  mark: "mark.svg",
  mark28: "mark-28.svg",
  wordmark: "wordmark.svg",
  lockup: "lockup.svg",
  lockupSidebar: "lockup-sidebar.svg",
} as const;

interface Shape {
  width: number;
  height: number;
  paths: string[];
}

function readShape(file: string): Shape {
  const svg = readFileSync(join(brandDir, file), "utf8");
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  if (!viewBox) throw new Error(`${file}: no viewBox`);
  const [x, y, width, height] = viewBox.trim().split(/[\s,]+/).map(Number);
  if (x !== 0 || y !== 0 || !width || !height) throw new Error(`${file}: the viewBox must start at 0 0`);
  if (/transform=/.test(svg)) throw new Error(`${file}: transforms are not supported, flatten the paths`);
  const paths = [...svg.matchAll(/<path\b[^>]*\sd="([^"]+)"/g)].map((m) => m[1] as string);
  if (paths.length === 0) throw new Error(`${file}: no path`);
  return { width, height, paths };
}

const shapes = Object.fromEntries(Object.entries(SHAPES).map(([name, file]) => [name, readShape(file)]));

const source = `// Generated by scripts/brand.ts from docs/brand/*.svg. Edit the SVGs and run \`bun scripts/brand.ts\`.

/** A drawn brand shape: paths in a viewBox that starts at 0 0, filled with the current colour. */
export interface BrandShape {
  readonly width: number;
  readonly height: number;
  readonly paths: readonly string[];
}

export const BRAND = ${JSON.stringify(shapes, null, 2)} as const satisfies Record<string, BrandShape>;
`;

writeFileSync(join(root, "packages", "shared", "src", "brand.ts"), source);
copyFileSync(join(brandDir, "favicon.svg"), join(root, "apps", "web", "public", "favicon.svg"));
console.log(`brand: ${Object.keys(shapes).join(", ")} written to packages/shared/src/brand.ts; favicon copied`);
